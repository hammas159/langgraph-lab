"""Run every dispatch strategy over every ticket, and write RESULTS.md.

    uv run python -m projects.p02_router_misroute.benchmark

The comparison that matters is clean tickets against cross-cutting ones, because a router that
is accurate on the first and confidently wrong on the second is not a router with a small error
rate — it is a router whose confidence is uninformative exactly where it is needed.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path

from projects.p02_router_misroute.graph import RunResult, run
from projects.p02_router_misroute.tickets import TICKETS, clean, cross_cutting
from shared.llm import Ledger, installed_tags, server_is_up
from shared.models import default_chat_model

HERE = Path(__file__).parent
RESULTS = HERE / "RESULTS.md"
RAW = HERE / "results.json"

STRATEGIES = ("single_pass", "confidence_gate", "multi_vote")


@dataclass
class Row:
    strategy: str
    group: str
    n: int
    correct: int
    escalated: int
    wrong_confident: int
    calls: int
    per_ticket: list = field(default_factory=list)

    @property
    def accuracy(self) -> float:
        return self.correct / self.n if self.n else 0.0

    @property
    def escalation_rate(self) -> float:
        return self.escalated / self.n if self.n else 0.0


def summarise(strategy: str, group: str, results: list[RunResult]) -> Row:
    return Row(
        strategy=strategy,
        group=group,
        n=len(results),
        correct=sum(r.correct for r in results),
        escalated=sum(r.escalated for r in results),
        wrong_confident=sum(r.wrong_and_confident for r in results),
        calls=sum(r.calls for r in results),
        per_ticket=[
            {
                "ticket": r.ticket.id,
                "primary": r.ticket.primary,
                "decision": r.decision,
                "correct": r.correct,
                "confidence": r.top_confidence,
                "votes": [v.category for v in r.votes],
            }
            for r in results
        ],
    )


def _pct(x: float) -> str:
    return f"{100 * x:.0f}%"


def render(rows: list[Row], elapsed: float, model: str) -> str:
    by = {(r.strategy, r.group): r for r in rows}
    out = ["# Results\n"]
    out.append("Generated by `projects/p02_router_misroute/benchmark.py`. Do not edit.\n")
    out.append(
        f"{len(STRATEGIES)} strategies x {len(TICKETS)} tickets on `{model}`. "
        f"{elapsed / 60:.1f} minutes.\n"
    )

    out.append("\n## Accuracy: clean tickets against cross-cutting ones\n")
    out.append(
        "`wrong+confident` is a misroute where the router also reported HIGH confidence — the "
        "case a confidence gate cannot catch by construction.\n"
    )
    out.append(
        "| strategy | clean acc. | cross-cutting acc. | escalated | wrong+confident | calls |"
    )
    out.append("|---|---|---|---|---|---|")
    for s in STRATEGIES:
        c, x = by.get((s, "clean")), by.get((s, "cross_cutting"))
        if not c or not x:
            continue
        out.append(
            f"| `{s}` | {_pct(c.accuracy)} | {_pct(x.accuracy)} | {_pct(x.escalation_rate)} "
            f"| {x.wrong_confident}/{x.n} | {c.calls + x.calls} |"
        )

    out.append("\n## Every cross-cutting ticket, every strategy\n")
    out.append("| ticket | primary | single_pass | confidence_gate | multi_vote |")
    out.append("|---|---|---|---|---|")
    ids = [t["ticket"] for t in by[("single_pass", "cross_cutting")].per_ticket]
    for tid in ids:
        row = [tid]
        primary = None
        for s in STRATEGIES:
            t = next(t for t in by[(s, "cross_cutting")].per_ticket if t["ticket"] == tid)
            primary = t["primary"]
            mark = "OK" if t["correct"] else t["decision"]
            conf = f" ({t['confidence']})" if t["confidence"] else ""
            row.append(f"{mark}{conf}")
        out.append(f"| {row[0]} | {primary} | {row[1]} | {row[2]} | {row[3]} |")

    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", default=None)
    args = parser.parse_args()

    if not server_is_up():
        print("ollama is not reachable.", file=sys.stderr)
        return 2
    model = args.model or default_chat_model()
    if model not in installed_tags():
        print(f"{model} is not pulled.", file=sys.stderr)
        return 2

    started = time.perf_counter()
    book = Ledger()
    rows: list[Row] = []

    for strategy in STRATEGIES:
        for group_name, tickets in (("clean", clean()), ("cross_cutting", cross_cutting())):
            print(f"  {strategy} / {group_name}", flush=True)
            results = []
            for ticket in tickets:
                try:
                    results.append(run(ticket, strategy=strategy, model=model, ledger=book))
                except Exception as exc:
                    print(f"    ! {ticket.id}: {exc}", file=sys.stderr)
            rows.append(summarise(strategy, group_name, results))

    elapsed = time.perf_counter() - started
    RAW.write_text(json.dumps([asdict(r) for r in rows], indent=2), encoding="utf-8")
    RESULTS.write_text(render(rows, elapsed, model), encoding="utf-8")
    print(f"\nwrote {RESULTS}  ({book.n_calls} model calls)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
