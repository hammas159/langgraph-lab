"""Run every stopping strategy over every task, and write RESULTS.md.

    uv run python -m projects.p01_revision_loops.benchmark

Four strategies, distinguished only by how the loop decides to stop:

    fixed_1    generate once, no revision. The baseline.
    fixed_3    always revise exactly 3 times, regardless of what the critique says.
    fixed_6    always revise 6 times — double the compute of fixed_3.
    self_stop  revise until the critique says COMPLETE, capped at 6 iterations.

The question is not "which scores highest" — more iterations can only help or do nothing on
average calls. It is whether the loop's own stopping signal (`self_stop`) tracks the ground
truth well enough to spend `fixed_6`'s compute only when it is still buying something, and
whether the score trajectory is actually monotonic, which every fixed-iteration design assumes
without checking.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path

from projects.p01_revision_loops.graph import RunResult, run
from projects.p01_revision_loops.tasks import TASKS
from shared.llm import Ledger, installed_tags, server_is_up
from shared.models import default_chat_model

HERE = Path(__file__).parent
RESULTS = HERE / "RESULTS.md"
RAW = HERE / "results.json"

STRATEGIES: dict[str, dict] = {
    "fixed_1": {"max_iterations": 0, "stop_on_complete": False},
    "fixed_3": {"max_iterations": 3, "stop_on_complete": False},
    "fixed_6": {"max_iterations": 6, "stop_on_complete": False},
    "self_stop": {"max_iterations": 6, "stop_on_complete": True},
}


@dataclass
class Row:
    strategy: str
    n: int
    mean_score: float
    mean_iterations: float
    mean_calls: float
    n_regressed: int
    n_lost_facts: int
    seconds: float
    per_task: list = field(default_factory=list)


def summarise(strategy: str, results: list[RunResult]) -> Row:
    n = len(results)
    return Row(
        strategy=strategy,
        n=n,
        mean_score=sum(r.final_score for r in results) / n,
        mean_iterations=sum(r.iterations for r in results) / n,
        mean_calls=sum(r.calls for r in results) / n,
        n_regressed=sum(1 for r in results if r.regressed),
        n_lost_facts=sum(len(r.lost_facts) for r in results),
        seconds=sum(r.seconds for r in results),
        per_task=[
            {
                "task": r.task.id,
                "final_score": round(r.final_score, 2),
                "iterations": r.iterations,
                "calls": r.calls,
                "trace": [round(s, 2) for s in r.score_trace],
                "regressed": r.regressed,
                "lost_facts": list(r.lost_facts),
            }
            for r in results
        ],
    )


def _pct(x: float) -> str:
    return f"{100 * x:.0f}%"


def render(rows: list[Row], elapsed: float, model: str) -> str:
    out = ["# Results\n"]
    out.append("Generated by `projects/p01_revision_loops/benchmark.py`. Do not edit.\n")
    out.append(
        f"{len(STRATEGIES)} strategies x {len(TASKS)} tasks on `{model}`. "
        f"{elapsed / 60:.1f} minutes.\n"
    )

    out.append("\n## Score against compute\n")
    out.append(
        "`mean score` is the fraction of each task's checklist present in the final answer. "
        "`regressed` is how many runs had the score go *down* at some point in the loop — a "
        "revision that lost a fact while fixing something else.\n"
    )
    out.append("| strategy | mean score | mean iterations | mean calls | regressed | facts lost |")
    out.append("|---|---|---|---|---|---|")
    for r in rows:
        out.append(
            f"| `{r.strategy}` | {_pct(r.mean_score)} | {r.mean_iterations:.1f} "
            f"| {r.mean_calls:.1f} | {r.n_regressed}/{r.n} | {r.n_lost_facts} |"
        )

    out.append("\n## Score trajectory per task\n")
    out.append("Each cell is the checklist score after each recorded iteration, in order.\n")
    for r in rows:
        out.append(f"\n**`{r.strategy}`**\n")
        out.append("| task | trace | final | regressed |")
        out.append("|---|---|---|---|")
        for t in r.per_task:
            trace_str = " -> ".join(f"{v:.2f}" for v in t["trace"]) or "(no revisions)"
            flag = "yes" if t["regressed"] else ""
            out.append(f"| {t['task']} | {trace_str} | {t['final_score']:.2f} | {flag} |")

    out.append("\n## Facts lost during revision\n")
    any_lost = False
    for r in rows:
        for t in r.per_task:
            if t["lost_facts"]:
                any_lost = True
                out.append(f"- `{r.strategy}` / {t['task']}: lost {', '.join(t['lost_facts'])}")
    if not any_lost:
        out.append("None in this run.\n")

    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", default=None)
    args = parser.parse_args()

    if not server_is_up():
        print("ollama is not reachable.", file=sys.stderr)
        return 2
    model = args.model or default_chat_model()
    if model not in installed_tags():
        print(f"{model} is not pulled.", file=sys.stderr)
        return 2

    started = time.perf_counter()
    book = Ledger()
    rows: list[Row] = []

    for label, kwargs in STRATEGIES.items():
        print(f"  {label}", flush=True)
        results = []
        for task in TASKS:
            try:
                results.append(run(task, strategy=label, model=model, ledger=book, **kwargs))
            except Exception as exc:
                print(f"    ! {task.id}: {exc}", file=sys.stderr)
        rows.append(summarise(label, results))

    elapsed = time.perf_counter() - started
    RAW.write_text(json.dumps([asdict(r) for r in rows], indent=2), encoding="utf-8")
    RESULTS.write_text(render(rows, elapsed, model), encoding="utf-8")
    print(f"\nwrote {RESULTS}  ({book.n_calls} model calls)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
