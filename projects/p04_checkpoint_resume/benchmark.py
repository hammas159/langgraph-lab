"""Run both resume strategies over every scenario, and write RESULTS.md.

    uv run python -m projects.p04_checkpoint_resume.benchmark

The number that matters is `draft_calls`: how many times the (real, costly) drafting node
actually ran across a full approve-with-revisions cycle, under a strategy that persists state
properly against one that re-invokes the whole graph from scratch on every round.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path

from projects.p04_checkpoint_resume.graph import RunResult, run_checkpointed, run_naive
from projects.p04_checkpoint_resume.scenarios import SCENARIOS
from shared.llm import installed_tags, server_is_up
from shared.models import default_chat_model

HERE = Path(__file__).parent
RESULTS = HERE / "RESULTS.md"
RAW = HERE / "results.json"


@dataclass
class Row:
    strategy: str
    total_draft_calls: int
    total_finalize_calls: int
    per_scenario: list = field(default_factory=list)


def summarise(strategy: str, results: list[RunResult]) -> Row:
    return Row(
        strategy=strategy,
        total_draft_calls=sum(r.draft_calls for r in results),
        total_finalize_calls=sum(r.finalize_calls for r in results),
        per_scenario=[
            {
                "scenario": r.scenario.id,
                "revision_rounds": len(r.rounds),
                "draft_calls": r.draft_calls,
                "finalize_calls": r.finalize_calls,
            }
            for r in results
        ],
    )


def render(rows: list[Row], elapsed: float, model: str) -> str:
    by = {r.strategy: r for r in rows}
    out = ["# Results\n"]
    out.append("Generated by `projects/p04_checkpoint_resume/benchmark.py`. Do not edit.\n")
    out.append(
        f"2 strategies x {len(SCENARIOS)} scenarios on `{model}`. {elapsed / 60:.1f} minutes.\n"
    )

    out.append("\n## Drafting calls per scenario\n")
    out.append(
        "`draft_calls` is how many times the drafting node actually ran — the number that "
        "would be a real LLM call, a real API call, or a real side effect in a production "
        "system. `finalize_calls` should be exactly 1 in both strategies; it is reported to "
        "confirm neither strategy double-finalises.\n"
    )
    out.append(
        "| scenario | revision rounds | checkpointed draft calls | naive draft calls | extra |"
    )
    out.append("|---|---|---|---|---|")
    ck_by_id = {s["scenario"]: s for s in by["checkpointed"].per_scenario}
    nv_by_id = {s["scenario"]: s for s in by["naive_requeue"].per_scenario}
    for sid in ck_by_id:
        ck, nv = ck_by_id[sid], nv_by_id[sid]
        out.append(
            f"| {sid} | {ck['revision_rounds']} | {ck['draft_calls']} | {nv['draft_calls']} "
            f"| +{nv['draft_calls'] - ck['draft_calls']} |"
        )

    out.append("\n## Totals\n")
    out.append("| strategy | total draft calls | total finalize calls |")
    out.append("|---|---|---|")
    for r in rows:
        out.append(f"| `{r.strategy}` | {r.total_draft_calls} | {r.total_finalize_calls} |")

    overhead = by["naive_requeue"].total_draft_calls - by["checkpointed"].total_draft_calls
    pct = 100 * overhead / by["checkpointed"].total_draft_calls
    out.append(
        f"\nNaive re-invocation cost **{overhead} extra drafting calls** across "
        f"{len(SCENARIOS)} scenarios — a **{pct:.0f}%** overhead over the checkpointed total, "
        "for behaviour that looks identical from outside a single request.\n"
    )

    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", default=None)
    args = parser.parse_args()

    if not server_is_up():
        print("ollama is not reachable.", file=sys.stderr)
        return 2
    model = args.model or default_chat_model()
    if model not in installed_tags():
        print(f"{model} is not pulled.", file=sys.stderr)
        return 2

    started = time.perf_counter()
    rows: list[Row] = []

    for strategy, fn in (("checkpointed", run_checkpointed), ("naive_requeue", run_naive)):
        print(f"  {strategy}", flush=True)
        results = []
        for scenario in SCENARIOS:
            try:
                results.append(fn(scenario, model=model))
            except Exception as exc:
                print(f"    ! {scenario.id}: {exc}", file=sys.stderr)
        rows.append(summarise(strategy, results))

    elapsed = time.perf_counter() - started
    RAW.write_text(json.dumps([asdict(r) for r in rows], indent=2), encoding="utf-8")
    RESULTS.write_text(render(rows, elapsed, model), encoding="utf-8")
    print(f"\nwrote {RESULTS}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
