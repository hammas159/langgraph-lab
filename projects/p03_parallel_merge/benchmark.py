"""Run every strategy over every brief, and write RESULTS.md.

    uv run python -m projects.p03_parallel_merge.benchmark

Three conditions, same graph:

    all_succeed    every analyst branch produces real content.
    fail_silent    one named branch fails (produces nothing); synthesis is not told to check.
    fail_flagged   the same failure; synthesis is explicitly told to name any missing section.

`disclosed` is the number under test: of the runs where a branch failed, how many reports said
so by name rather than reading as a complete four-aspect memo with one aspect quietly absent.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path

from projects.p03_parallel_merge.briefs import ASPECTS, BRIEFS
from projects.p03_parallel_merge.graph import RunResult, run
from shared.llm import Ledger, installed_tags, server_is_up
from shared.models import default_chat_model

HERE = Path(__file__).parent
RESULTS = HERE / "RESULTS.md"
RAW = HERE / "results.json"

#: Rotate which aspect fails across briefs so the finding is not an artefact of always
#: silencing the same branch.
FAIL_ROTATION = dict(zip((b.id for b in BRIEFS), ASPECTS * 2, strict=False))


@dataclass
class Row:
    strategy: str
    n: int
    mean_represented: float
    n_disclosed: int
    n_failed_runs: int
    n_reads_complete: int
    calls: int
    per_brief: list = field(default_factory=list)


def summarise(strategy: str, results: list[RunResult]) -> Row:
    failed_runs = [r for r in results if r.fail_aspect]
    return Row(
        strategy=strategy,
        n=len(results),
        mean_represented=sum(len(r.represented_aspects) for r in results) / len(results),
        n_disclosed=sum(r.missing_aspect_disclosed for r in failed_runs),
        n_failed_runs=len(failed_runs),
        n_reads_complete=sum(r.reads_as_complete for r in failed_runs),
        calls=sum(r.calls for r in results),
        per_brief=[
            {
                "brief": r.brief.id,
                "fail_aspect": r.fail_aspect,
                "represented": list(r.represented_aspects),
                "disclosed": r.missing_aspect_disclosed,
                "reads_complete": r.reads_as_complete,
            }
            for r in results
        ],
    )


def _pct(part: int, whole: int) -> str:
    return f"{100 * part / whole:.0f}%" if whole else "n/a"


def render(rows: list[Row], elapsed: float, model: str) -> str:
    out = ["# Results\n"]
    out.append("Generated by `projects/p03_parallel_merge/benchmark.py`. Do not edit.\n")
    out.append(f"3 strategies x {len(BRIEFS)} briefs on `{model}`. {elapsed / 60:.1f} minutes.\n")

    out.append("\n## Disclosure of a failed branch\n")
    out.append(
        "`reads as complete` is the dangerous case: a branch produced nothing, and the report "
        "covers all four aspects by name anyway, with no indication anything was missing.\n"
    )
    out.append(
        "| strategy | mean aspects represented (of 4) | disclosed failure | reads as complete |"
    )
    out.append("|---|---|---|---|")
    for r in rows:
        disc = _pct(r.n_disclosed, r.n_failed_runs) if r.n_failed_runs else "n/a"
        complete = f"{r.n_reads_complete}/{r.n_failed_runs}" if r.n_failed_runs else "n/a"
        out.append(f"| `{r.strategy}` | {r.mean_represented:.2f} | {disc} | {complete} |")

    out.append("\n## Every run\n")
    out.append("| strategy | brief | failed branch | represented | disclosed |")
    out.append("|---|---|---|---|---|")
    for r in rows:
        for b in r.per_brief:
            out.append(
                f"| `{r.strategy}` | {b['brief']} | {b['fail_aspect'] or '—'} "
                f"| {', '.join(b['represented']) or 'none'} "
                f"| {'yes' if b['disclosed'] else ('n/a' if not b['fail_aspect'] else 'no')} |"
            )

    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", default=None)
    args = parser.parse_args()

    if not server_is_up():
        print("ollama is not reachable.", file=sys.stderr)
        return 2
    model = args.model or default_chat_model()
    if model not in installed_tags():
        print(f"{model} is not pulled.", file=sys.stderr)
        return 2

    started = time.perf_counter()
    book = Ledger()
    rows: list[Row] = []

    for strategy, flag_gaps, use_fail in (
        ("all_succeed", False, False),
        ("fail_silent", False, True),
        ("fail_flagged", True, True),
    ):
        print(f"  {strategy}", flush=True)
        results = []
        for brief in BRIEFS:
            fail_aspect = FAIL_ROTATION[brief.id] if use_fail else ""
            try:
                results.append(
                    run(
                        brief,
                        strategy=strategy,
                        fail_aspect=fail_aspect,
                        flag_gaps=flag_gaps,
                        model=model,
                        ledger=book,
                    )
                )
            except Exception as exc:
                print(f"    ! {brief.id}: {exc}", file=sys.stderr)
        rows.append(summarise(strategy, results))

    elapsed = time.perf_counter() - started
    RAW.write_text(json.dumps([asdict(r) for r in rows], indent=2), encoding="utf-8")
    RESULTS.write_text(render(rows, elapsed, model), encoding="utf-8")
    print(f"\nwrote {RESULTS}  ({book.n_calls} model calls)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
