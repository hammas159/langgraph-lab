"""Run every handoff strategy over every case, and write RESULTS.md.

    uv run python -m projects.p05_supervisor_handoff.benchmark

`violated` is scored only against responses that engaged with the topic, because a response
that has lost the thread entirely mentions no forbidden term by having said nothing relevant —
which would otherwise look identical to a genuinely safe answer. `safe_and_relevant` is the
only number that cannot be gamed by going silent on the constraint.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path

from projects.p05_supervisor_handoff.cases import CASES
from projects.p05_supervisor_handoff.graph import RunResult, run
from shared.llm import installed_tags, server_is_up
from shared.models import default_chat_model

HERE = Path(__file__).parent
RESULTS = HERE / "RESULTS.md"
RAW = HERE / "results.json"

STRATEGIES = ("full_transcript", "summary_handoff", "last_message_only")


@dataclass
class Row:
    strategy: str
    n: int
    n_on_topic: int
    n_violated: int
    n_safe_and_relevant: int
    per_case: list = field(default_factory=list)

    @property
    def on_topic_rate(self) -> float:
        return self.n_on_topic / self.n if self.n else 0.0

    @property
    def safe_rate(self) -> float:
        return self.n_safe_and_relevant / self.n if self.n else 0.0


def summarise(strategy: str, results: list[RunResult]) -> Row:
    return Row(
        strategy=strategy,
        n=len(results),
        n_on_topic=sum(r.stayed_on_topic for r in results),
        n_violated=sum(r.violated for r in results),
        n_safe_and_relevant=sum(r.safe_and_relevant for r in results),
        per_case=[
            {
                "case": r.case.id,
                "constraint": r.case.constraint,
                "on_topic": r.stayed_on_topic,
                "violated": r.violated,
                "safe_and_relevant": r.safe_and_relevant,
                "response": r.response,
            }
            for r in results
        ],
    )


def _pct(part: int, whole: int) -> str:
    return f"{100 * part / whole:.0f}%" if whole else "n/a"


def render(rows: list[Row], elapsed: float, model: str) -> str:
    by = {r.strategy: r for r in rows}
    out = ["# Results\n"]
    out.append("Generated by `projects/p05_supervisor_handoff/benchmark.py`. Do not edit.\n")
    out.append(
        f"3 handoff strategies x {len(CASES)} cases on `{model}`. {elapsed / 60:.1f} minutes.\n"
    )

    out.append("\n## Constraint safety by handoff strategy\n")
    out.append(
        "`safe_and_relevant` requires both: the response engaged with the topic **and** did "
        "not break the constraint. Neither number alone is trustworthy — a response that goes "
        "silent on the topic never breaks a constraint either.\n"
    )
    out.append("| strategy | stayed on topic | broke the constraint | safe and relevant |")
    out.append("|---|---|---|---|")
    for s in STRATEGIES:
        r = by[s]
        out.append(
            f"| `{s}` | {_pct(r.n_on_topic, r.n)} | {_pct(r.n_violated, r.n)} "
            f"| {_pct(r.n_safe_and_relevant, r.n)} |"
        )

    out.append("\n## Every case\n")
    out.append("| case | constraint | full_transcript | summary_handoff | last_message_only |")
    out.append("|---|---|---|---|---|")
    ids = [c["case"] for c in by["full_transcript"].per_case]
    for cid in ids:
        cells = []
        constraint = ""
        for s in STRATEGIES:
            c = next(c for c in by[s].per_case if c["case"] == cid)
            constraint = c["constraint"]
            if not c["on_topic"]:
                cells.append("off-topic")
            elif c["violated"]:
                cells.append("VIOLATED")
            else:
                cells.append("ok")
        out.append(f"| {cid} | {constraint} | {cells[0]} | {cells[1]} | {cells[2]} |")

    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", default=None)
    args = parser.parse_args()

    if not server_is_up():
        print("ollama is not reachable.", file=sys.stderr)
        return 2
    model = args.model or default_chat_model()
    if model not in installed_tags():
        print(f"{model} is not pulled.", file=sys.stderr)
        return 2

    started = time.perf_counter()
    rows: list[Row] = []

    for strategy in STRATEGIES:
        print(f"  {strategy}", flush=True)
        results = []
        for case in CASES:
            try:
                results.append(run(case, strategy=strategy, model=model))
            except Exception as exc:
                print(f"    ! {case.id}: {exc}", file=sys.stderr)
        rows.append(summarise(strategy, results))

    elapsed = time.perf_counter() - started
    RAW.write_text(json.dumps([asdict(r) for r in rows], indent=2), encoding="utf-8")
    RESULTS.write_text(render(rows, elapsed, model), encoding="utf-8")
    print(f"\nwrote {RESULTS}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
